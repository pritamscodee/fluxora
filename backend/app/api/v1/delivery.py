"""Public delivery surface.

Every byte a viewer receives passes through here, which is what makes a single chokepoint
for playback policy, signed-token audience checks, and analytics possible (ADR-0001).

Segment URIs are immutable and content-addressed by filename, so they get a long
`Cache-Control`; manifests get a short one so a future live/trimmed variant stays correct.
"""

from __future__ import annotations

import re
from pathlib import Path
from tempfile import TemporaryDirectory

from fastapi import APIRouter, Query, Request, Response
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.deps import DbSession
from app.core.config import settings
from app.core.errors import Conflict, Forbidden, InvalidParameters, NotFound
from app.core.security import (
    AUD_GIF,
    AUD_STORYBOARD,
    AUD_THUMBNAIL,
    AUD_VIDEO,
    playback_token_key_id,
    verify_playback_token,
)
from app.models import Asset, PlaybackId, SigningKey
from app.schemas.common import envelope
from app.services import media, storage

router = APIRouter(tags=["delivery"])

IMMUTABLE = "public, max-age=31536000, immutable"
SHORT_CACHE = "public, max-age=60"

# Filenames are generated by media.build_hls_argv; anything else is rejected outright
# rather than passed to the storage layer.
HLS_FILENAME = re.compile(
    r"^(?:master\.m3u8|[A-Za-z0-9]{2,12}_(?:playlist\.m3u8|init\.mp4|segment_\d{5}\.m4s))$"
)

CONTENT_TYPES = {
    ".m3u8": "application/vnd.apple.mpegurl",
    ".m4s": "video/iso.segment",
    ".mp4": "video/mp4",
    ".jpg": "image/jpeg",
    ".png": "image/png",
    ".gif": "image/gif",
    ".vtt": "text/vtt",
}


async def _resolve(
    db: AsyncSession, playback_id: str, audience: str, token: str | None
) -> tuple[Asset, PlaybackId]:
    row = await db.scalar(select(PlaybackId).where(PlaybackId.id == playback_id))
    if row is None or row.asset_id is None:
        raise NotFound("playback id was not found")

    asset = await db.scalar(select(Asset).where(Asset.id == row.asset_id))
    if asset is None or asset.status == "deleted":
        raise NotFound("playback id was not found")

    if row.policy == "signed":
        if not token:
            raise Forbidden("this playback id requires a signed token")
        key_id = playback_token_key_id(token)
        if not key_id:
            raise Forbidden("playback token is missing a key id")
        key = await db.scalar(
            select(SigningKey).where(
                SigningKey.id == key_id,
                SigningKey.project_id == asset.project_id,
                SigningKey.revoked_at.is_(None),
            )
        )
        if key is None:
            # Covers an unknown key, a revoked key, and a key belonging to another
            # project — all of which are the same answer to the caller.
            raise Forbidden("playback token was signed with an unrecognised key")
        verify_playback_token(token, key.public_key_pem, playback_id, audience)

    if asset.status != "ready":
        raise Conflict(f"asset is not ready for playback (status: {asset.status})")
    return asset, row


def _content_type(name: str) -> str:
    return CONTENT_TYPES.get(Path(name).suffix, "application/octet-stream")


@router.get("/stream/{playback_id}.m3u8")
async def master_manifest(
    playback_id: str, db: DbSession, token: str | None = Query(default=None)
):
    asset, _ = await _resolve(db, playback_id, AUD_VIDEO, token)
    key = storage.master_manifest_key(asset.project_id, asset.id)
    try:
        body = await storage.get_storage().get_bytes(key)
    except Exception as exc:
        raise NotFound("playback manifest is not available for this asset") from exc

    # Variant URIs in the stored manifest are bare filenames; rewrite them onto this
    # playback id so the token (and the policy attached to it) travels with every request.
    suffix = f"?token={token}" if token else ""
    rewritten = "\n".join(
        f"{playback_id}/{line}{suffix}"
        if line and not line.startswith("#") and line.endswith(".m3u8")
        else line
        for line in body.decode().splitlines()
    )
    return Response(
        content=rewritten,
        media_type=CONTENT_TYPES[".m3u8"],
        headers={"Cache-Control": SHORT_CACHE},
    )


@router.get("/stream/{playback_id}/{filename}")
async def hls_file(
    playback_id: str,
    filename: str,
    db: DbSession,
    request: Request,
    token: str | None = Query(default=None),
):
    """Serves variant playlists, fMP4 init segments, and media segments."""
    if not HLS_FILENAME.match(filename):
        # Derived outputs live on their own routes; route them there rather than 404ing.
        return await _derived(playback_id, filename, db, request, token)

    asset, _ = await _resolve(db, playback_id, AUD_VIDEO, token)
    key = storage.hls_file_key(asset.project_id, asset.id, filename)
    try:
        body = await storage.get_storage().get_bytes(key)
    except Exception as exc:
        raise NotFound(f"{filename} is not available for this asset") from exc

    if filename.endswith(".m3u8"):
        cache = SHORT_CACHE
        if token:
            # Keep the token on segment requests inside a variant playlist.
            body = "\n".join(
                f"{line}?token={token}"
                if line and not line.startswith("#") and not line.endswith(".m3u8")
                else line
                for line in body.decode().splitlines()
            ).encode()
    else:
        cache = IMMUTABLE

    return Response(
        content=body,
        media_type=_content_type(filename),
        headers={"Cache-Control": cache},
    )


async def _derived(
    playback_id: str, filename: str, db: AsyncSession, request: Request, token: str | None
) -> Response:
    if filename in {"thumbnail.jpg", "thumbnail.png"}:
        return await _thumbnail(playback_id, filename, db, request, token)
    if filename == "animated.gif":
        return await _animated_gif(playback_id, db, request, token)
    if filename in {"storyboard.vtt", "storyboard.jpg"}:
        return await _storyboard(playback_id, filename, db, token)
    if filename.endswith(".mp4"):
        return await _static_rendition(playback_id, filename, db, token)
    raise NotFound(f"{filename} is not a recognised delivery path")


async def _source_copy(asset: Asset, scratch: Path) -> Path:
    """Pull whatever we can render frames from: the retained source if we still have it,
    otherwise the top HLS rendition."""
    store = storage.get_storage()
    if asset.source_key and await store.exists(asset.source_key):
        return await store.download(asset.source_key, scratch / "source")

    master_key = storage.master_manifest_key(asset.project_id, asset.id)
    manifest = (await store.get_bytes(master_key)).decode()
    variants = [ln.strip() for ln in manifest.splitlines() if ln.strip().endswith(".m3u8")]
    if not variants:
        raise NotFound("no renderable media is available for this asset")
    rendition = variants[-1].removesuffix("_playlist.m3u8")

    local = scratch / "rendition"
    local.mkdir(parents=True, exist_ok=True)
    playlist_name = f"{rendition}_playlist.m3u8"
    playlist_text = (
        await store.get_bytes(
            storage.hls_file_key(asset.project_id, asset.id, playlist_name)
        )
    ).decode()
    (local / playlist_name).write_text(playlist_text)
    for line in playlist_text.splitlines():
        name = line.strip()
        if not name or name.startswith("#"):
            if name.startswith("#EXT-X-MAP:URI="):
                name = name.split('"')[1]
            else:
                continue
        await store.download(
            storage.hls_file_key(asset.project_id, asset.id, name), local / name
        )
    return local / playlist_name


async def _thumbnail(
    playback_id: str, filename: str, db: AsyncSession, request: Request, token: str | None
) -> Response:
    asset, _ = await _resolve(db, playback_id, AUD_THUMBNAIL, token)
    q = request.query_params
    try:
        time_offset = float(q.get("time", 0) or 0)
        width = int(q["width"]) if q.get("width") else None
        height = int(q["height"]) if q.get("height") else None
    except ValueError as exc:
        raise InvalidParameters("time, width and height must be numbers") from exc

    fit_mode = q.get("fit_mode", "preserve")
    if fit_mode not in {"preserve", "crop", "pad", "smartcrop"}:
        raise InvalidParameters("fit_mode must be one of preserve, crop, pad, smartcrop")
    for name, value in (("width", width), ("height", height)):
        if value is not None and not 16 <= value <= 3840:
            raise InvalidParameters(f"{name} must be between 16 and 3840")
    if asset.duration and time_offset > asset.duration:
        raise InvalidParameters(
            f"time {time_offset}s is beyond the asset duration of {asset.duration:.3f}s"
        )

    store = storage.get_storage()
    spec = f"{time_offset}:{width}:{height}:{fit_mode}"
    cache_key = storage.thumbnail_key(asset.project_id, asset.id, spec)
    if await store.exists(cache_key):
        return Response(
            content=await store.get_bytes(cache_key),
            media_type=CONTENT_TYPES[".jpg"],
            headers={"Cache-Control": IMMUTABLE, "X-Fluxora-Cache": "hit"},
        )

    with TemporaryDirectory(dir=settings.media_scratch_dir) as tmp:
        scratch = Path(tmp)
        source = await _source_copy(asset, scratch)
        dest = scratch / "thumb.jpg"
        await media.extract_thumbnail(
            source, dest, time_offset, width, height,
            "crop" if fit_mode == "smartcrop" else fit_mode,
        )
        body = dest.read_bytes()
        await store.put_bytes(cache_key, body, "image/jpeg")

    return Response(
        content=body,
        media_type=CONTENT_TYPES[".jpg"],
        headers={"Cache-Control": IMMUTABLE, "X-Fluxora-Cache": "miss"},
    )


async def _animated_gif(
    playback_id: str, db: AsyncSession, request: Request, token: str | None
) -> Response:
    asset, _ = await _resolve(db, playback_id, AUD_GIF, token)
    q = request.query_params
    try:
        start = float(q.get("start", 0) or 0)
        end = float(q.get("end", start + 5) or start + 5)
        width = int(q.get("width", 320) or 320)
        fps = int(q.get("fps", 15) or 15)
    except ValueError as exc:
        raise InvalidParameters("start, end, width and fps must be numbers") from exc
    if end <= start:
        raise InvalidParameters("end must be greater than start")
    if end - start > 10:
        raise InvalidParameters("an animated GIF may span at most 10 seconds")
    if not 16 <= width <= 1920:
        raise InvalidParameters("width must be between 16 and 1920")
    if not 1 <= fps <= 30:
        raise InvalidParameters("fps must be between 1 and 30")

    with TemporaryDirectory(dir=settings.media_scratch_dir) as tmp:
        scratch = Path(tmp)
        source = await _source_copy(asset, scratch)
        dest = scratch / "animated.gif"
        await media.extract_gif(source, dest, start, end, width, fps)
        body = dest.read_bytes()
    return Response(
        content=body, media_type=CONTENT_TYPES[".gif"],
        headers={"Cache-Control": IMMUTABLE},
    )


async def _storyboard(
    playback_id: str, filename: str, db: AsyncSession, token: str | None
) -> Response:
    asset, _ = await _resolve(db, playback_id, AUD_STORYBOARD, token)
    ext = "vtt" if filename.endswith(".vtt") else "jpg"
    key = f"{storage.asset_prefix(asset.project_id, asset.id)}/storyboard.{ext}"
    store = storage.get_storage()
    if not await store.exists(key):
        raise NotFound(
            "a storyboard has not been generated for this asset yet"
        )
    body = await store.get_bytes(key)
    if ext == "vtt":
        # Rewrite the sprite reference onto this playback id.
        body = body.decode().replace(
            "storyboard.jpg", f"/v1/stream/{playback_id}/storyboard.jpg"
        ).encode()
    return Response(
        content=body,
        media_type=CONTENT_TYPES[f".{ext}"],
        headers={"Cache-Control": IMMUTABLE},
    )


async def _static_rendition(
    playback_id: str, filename: str, db: AsyncSession, token: str | None
) -> Response:
    from app.models import StaticRendition

    asset, _ = await _resolve(db, playback_id, AUD_VIDEO, token)
    name = filename.removesuffix(".mp4")
    rendition = await db.scalar(
        select(StaticRendition).where(
            StaticRendition.asset_id == asset.id,
            StaticRendition.name == name,
            StaticRendition.status == "ready",
        )
    )
    if rendition is None or not rendition.object_key:
        raise NotFound(f"static rendition {name!r} is not available for this asset")
    body = await storage.get_storage().get_bytes(rendition.object_key)
    return Response(
        content=body,
        media_type=CONTENT_TYPES[".mp4"],
        headers={"Cache-Control": IMMUTABLE, "Accept-Ranges": "bytes"},
    )


@router.get("/video/playback-ids/{playback_id}")
async def resolve_playback_id(playback_id: str, db: DbSession):
    row = await db.scalar(select(PlaybackId).where(PlaybackId.id == playback_id))
    if row is None:
        raise NotFound("playback id was not found")
    object_type = "asset" if row.asset_id else "live_stream"
    return envelope(
        {
            "object": {"type": object_type, "id": row.asset_id or row.live_stream_id},
            "policy": row.policy,
        }
    )
